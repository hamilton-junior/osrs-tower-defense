/**
 * Bakes lib/game/data/npc-hitpoints.data.ts: each baked enemy's real OSRS
 * hitpoints, read from the NPC def of the exact id its sprites were rendered
 * from (scripts/enemy-anims.config.json). The lobby's stray shot deals this to
 * fell a monster in one hit, so the splat shows the number the Wiki shows.
 *
 * Reads the local cache through @abextm/cache2 (see scripts/lib/npc-def.mjs);
 * run it again whenever the config gains an enemy.
 *
 *   node scripts/bake-npc-hitpoints.mjs
 */
import { NPC } from '@abextm/cache2';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { defsCache } from './lib/npc-def.mjs';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..');
const config = JSON.parse(readFileSync(join(REPO, 'scripts', 'enemy-anims.config.json'), 'utf8'));
const cache = await defsCache();

const rows = [];
const missing = [];
for (const [slug, entry] of Object.entries(config)) {
  const def = await NPC.load(cache, entry.npc);
  const hp = def?.hitpoints ?? 0;
  if (hp > 0) rows.push(`  ${slug}: ${hp}, // ${def.name} (NPC ${entry.npc})`);
  else missing.push(`${slug} (NPC ${entry.npc})`);
}

const out = `// AUTO-GENERATED by scripts/bake-npc-hitpoints.mjs. Do not edit by hand.
// Real OSRS hitpoints per baked enemy, read from the cache NPC def of the id its
// sprites were rendered from. ${rows.length} enemies.

export const NPC_HITPOINTS: Record<string, number> = {
${rows.join('\n')}
};
`;
writeFileSync(join(REPO, 'lib', 'game', 'data', 'npc-hitpoints.data.ts'), out);
console.log(`wrote ${rows.length} entries`);
if (missing.length) console.log(`no hitpoints: ${missing.join(', ')}`);
