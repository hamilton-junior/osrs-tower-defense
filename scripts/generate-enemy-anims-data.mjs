/**
 * Regenerate lib/game/data/enemy-anims.data.ts from the baked per-enemy
 * manifests (public/assets/enemies/<slug>/<slug>.json). Run after re-baking:
 *
 *   node scripts/render-osrs-npc-anims.mjs --only <slug>   # re-bake the sheets
 *   node scripts/generate-enemy-anims-data.mjs             # regenerate the table
 *
 * Enemy order follows scripts/enemy-anims.config.json; clips emit in
 * walk/hurt/death order; each frameMs is capped at 400 (a long held death-pose
 * otherwise stalls the playback loop).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = join(__dirname, '..');
const config = JSON.parse(readFileSync(join(__dirname, 'enemy-anims.config.json'), 'utf8'));
const CLIP_ORDER = ['walk', 'hurt', 'death'];
const CAP = 400;

let clipCount = 0;
const blocks = [];
for (const slug of Object.keys(config)) {
  const manifestPath = join(REPO, 'public', 'assets', 'enemies', slug, `${slug}.json`);
  if (!existsSync(manifestPath)) { console.warn(`! no manifest for ${slug}`); continue; }
  const m = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const lines = [];
  for (const name of CLIP_ORDER) {
    const c = m.clips[name];
    if (!c) continue;
    clipCount++;
    const ms = c.frameMs.map((v) => Math.min(v, CAP));
    lines.push(
      `      ${name}: { url: \`\${B}/${slug}/${name}.png\`, frames: ${c.frames}, frameMs: [${ms.join(', ')}], loop: ${!!c.loop} },`,
    );
  }
  blocks.push(
    `  ${slug}: {\n    frameW: ${m.frameW}, frameH: ${m.frameH},\n    clips: {\n${lines.join('\n')}\n    },\n  },`,
  );
}

const out = `// AUTO-GENERATED by scripts/render-osrs-npc-anims.mjs + scripts/generate-enemy-anims-data.mjs.
// Do not edit by hand — re-bake and regenerate. ${blocks.length} enemies, ${clipCount} clips.
// Per-enemy animation sheets baked from the OSRS cache (walk loop + optional
// hurt flinch + death collapse). See lib/game/data/enemy-anims.ts for the
// playback helpers and the EnemyAnimSet contract.
import type { EnemyAnimSet } from './enemy-anims';

const B = \`\${process.env.NEXT_PUBLIC_BASE_PATH || ''}/assets/enemies\`;

export const ENEMY_ANIMS: Record<string, EnemyAnimSet> = {
${blocks.join('\n')}
};
`;

writeFileSync(join(REPO, 'lib', 'game', 'data', 'enemy-anims.data.ts'), out);
console.log(`wrote enemy-anims.data.ts (${blocks.length} enemies, ${clipCount} clips)`);
