/**
 * Regenerate a baked animation table from the per-slug manifests written by the
 * baker (public/assets/<group>/<slug>/<slug>.json). Run after re-baking:
 *
 *   node scripts/bake-enemy-sprites-from-gltf.mjs --only <slug>   # re-bake the sheets
 *   node scripts/generate-enemy-anims-data.mjs                    # regenerate the table
 *   node scripts/generate-enemy-anims-data.mjs --group diversions
 *
 * Order follows the group's config file; clips emit in the group's clip order; each
 * frameMs is capped at 400 (a long held death-pose otherwise stalls the playback loop).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { pickGroup } from './lib/anim-group.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = join(__dirname, '..');
const GROUP = pickGroup(process.argv);
const config = JSON.parse(readFileSync(join(__dirname, GROUP.config), 'utf8'));
// For the enemies, beyond walk/hurt/death these are **mechanic clips**: a boss phase whose
// animation is the mechanic, played instead of the walk for the duration of that phase (see
// `bossPhaseClip`). `burrow`/`emerge` are the Giant Mole going under and coming back up
// (OSRS anims 3314/3315); `rage`/`charge` are Brutus pawing the ground and galloping
// (13780/13793); `breath` is the King Black Dragon rearing back to breathe (81).
// A new one here also needs a slot in `EnemyAnimSet.clips` in data/enemy-anims.ts.
const CLIP_ORDER = GROUP.clipOrder;
const CAP = 400;

/** One clip's TS literal. `prefix` names the sheet inside a multi-view group. */
function clipLine(slug, name, c, indent, prefix = '') {
  const ms = c.frameMs.map((v) => Math.min(v, CAP));
  return `${indent}${name}: { url: \`\${B}/${slug}/${prefix}${name}.png\`, frames: ${c.frames}, frameMs: [${ms.join(', ')}], loop: ${!!c.loop} },`;
}

let clipCount = 0;
const blocks = [];
for (const slug of Object.keys(config)) {
  const manifestPath = join(REPO, ...GROUP.spriteDir, slug, `${slug}.json`);
  if (!existsSync(manifestPath)) { console.warn(`! no manifest for ${slug}`); continue; }
  const m = JSON.parse(readFileSync(manifestPath, 'utf8'));

  if (!GROUP.views) {
    const lines = [];
    for (const name of CLIP_ORDER) {
      const c = m.clips?.[name];
      if (!c) continue;
      clipCount++;
      lines.push(clipLine(slug, name, c, '      '));
    }
    blocks.push(`  ${slug}: {\n    frameW: ${m.frameW}, frameH: ${m.frameH},\n    clips: {\n${lines.join('\n')}\n    },\n  },`);
    continue;
  }

  const views = [];
  for (const view of Object.keys(GROUP.views)) {
    const set = m.views?.[view];
    if (!set) continue;
    const lines = [];
    for (const name of CLIP_ORDER) {
      const c = set[name];
      if (!c) continue;
      clipCount++;
      lines.push(clipLine(slug, name, c, '        ', `${view}-`));
    }
    views.push(`      ${view}: {\n${lines.join('\n')}\n      },`);
  }
  blocks.push(`  ${slug}: {\n    frameW: ${m.frameW}, frameH: ${m.frameH},\n    views: {\n${views.join('\n')}\n    },\n  },`);
}

const header = GROUP.views
  ? `// Per-view animation sheets baked from the OSRS cache: one loop per camera yaw, so
// a walker can face the way it is going. See lib/game/data/diversion-anims.ts for the
// contract; playback reuses the enemy helpers.`
  : `// Per-enemy animation sheets baked from the OSRS cache (walk loop + optional
// hurt flinch + death collapse). See lib/game/data/enemy-anims.ts for the
// playback helpers and the EnemyAnimSet contract.`;

const out = `// AUTO-GENERATED by scripts/bake-enemy-sprites-from-gltf.mjs + scripts/generate-enemy-anims-data.mjs.
// Do not edit by hand — re-bake and regenerate. ${blocks.length} ${GROUP.label}, ${clipCount} clips.
${header}
import type { ${GROUP.typeName} } from '${GROUP.typeModule}';

const B = \`\${process.env.NEXT_PUBLIC_BASE_PATH || ''}${GROUP.urlBase}\`;

export const ${GROUP.table}: Record<string, ${GROUP.typeName}> = {
${blocks.join('\n')}
};
`;

writeFileSync(join(REPO, ...GROUP.dataFile), out);
console.log(`wrote ${GROUP.dataFile.at(-1)} (${blocks.length} ${GROUP.label}, ${clipCount} clips)`);
