/**
 * Regenerate lib/game/data/spotanims.data.ts from the baked spotanim sidecars
 * (public/assets/spotanims/*.json). Run after re-baking:
 *
 *   node scripts/render-osrs-spotanims.mjs            # re-bake the sheets
 *   node scripts/generate-spotanims-data.mjs          # regenerate the table
 *
 * Emits raw sheet facts only (frames/frameW/frameH/frameMs); presentation
 * (draw size, speed, blend, loop) lives in lib/game/data/spotanims.ts.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, basename } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = join(__dirname, '..');
const DIR = join(REPO, 'public', 'assets', 'spotanims');

const blocks = [];
const slugs = readdirSync(DIR).filter((f) => f.endsWith('.json')).map((f) => basename(f, '.json')).sort();
for (const slug of slugs) {
  const m = JSON.parse(readFileSync(join(DIR, `${slug}.json`), 'utf8'));
  blocks.push(
    `  ${slug}: { url: \`\${B}/${slug}.png\`, frames: ${m.frames}, frameW: ${m.frameW}, frameH: ${m.frameH}, frameMs: [${m.frameMs.join(', ')}] },`,
  );
}

const out = `// AUTO-GENERATED by scripts/render-osrs-spotanims.mjs + scripts/generate-spotanims-data.mjs.
// Do not edit by hand — re-bake and regenerate. ${slugs.length} sheets.
// Raw sheet facts for every baked spotanim (GFX) sprite sheet; presentation
// (draw size, speed, blend, loop) is layered on in lib/game/data/spotanims.ts.

export interface SpotAnimSheet {
  url: string;
  frames: number;
  frameW: number;
  frameH: number;
  /** Authentic per-frame durations (ms) from the cache sequence. */
  frameMs: number[];
}

const B = \`\${process.env.NEXT_PUBLIC_BASE_PATH || ''}/assets/spotanims\`;

export const SPOTANIM_SHEETS: Record<string, SpotAnimSheet> = {
${blocks.join('\n')}
};
`;
writeFileSync(join(REPO, 'lib', 'game', 'data', 'spotanims.data.ts'), out);
console.log(`✓ lib/game/data/spotanims.data.ts — ${slugs.length} sheets`);
